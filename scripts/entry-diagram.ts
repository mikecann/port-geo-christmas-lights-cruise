// Writes the entry machine's Mermaid diagram to docs/entry-machine.md, drawn
// from the same rules the app runs. Run it after changing the machine:
//   bun scripts/entry-diagram.ts
import { writeFileSync } from "node:fs";
import { stateDiagram } from "@convex-dev/state-machines";
import { entry, machines } from "../convex/machines";

const target = new URL("../docs/entry-machine.md", import.meta.url);

const markdown = `# The entry machine

A competition entry's lifecycle, as \`convex/features/entries/machine.ts\` defines it. Generated by \`bun scripts/entry-diagram.ts\`: don't edit it by hand.

The owner is the entrant, the admin is a competition admin, and \`server\` is the submit action reporting back once it has looked the address up with Google. Each state lists the data it keeps.

\`\`\`mermaid
${stateDiagram(entry.manifest, machines.manifests)}
\`\`\`
`;

writeFileSync(target, markdown);
console.log(`Wrote ${target.pathname}`);
